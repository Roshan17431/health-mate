-- Synthetic PostgreSQL legacy schema: the nine JPA tables before the two
-- operator migrations. No application seed, real patient data or secrets.
CREATE TABLE public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255), email varchar(255) NOT NULL UNIQUE, password varchar(255),
    phone_number varchar(255) NOT NULL UNIQUE, role varchar(255) NOT NULL,
    gender varchar(255) NOT NULL, date_of_birth date NOT NULL,
    address varchar(255) NOT NULL, created_date timestamp(6), updated_date timestamp(6)
);
CREATE TABLE public.doctors (
    user_id bigint PRIMARY KEY REFERENCES public.users(id),
    experience integer NOT NULL, available_hours varchar(255) NOT NULL,
    specialization varchar(255) NOT NULL, created_at timestamp(6), updated_at timestamp(6)
);
CREATE TABLE public.patients (
    user_id bigint PRIMARY KEY REFERENCES public.users(id),
    created_at timestamp(6), updated_at timestamp(6)
);
CREATE TABLE public.doctor_schedules (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id bigint NOT NULL REFERENCES public.doctors(user_id),
    day_of_week varchar(255) NOT NULL, start_time time(6) NOT NULL,
    end_time time(6) NOT NULL, is_active boolean NOT NULL,
    created_at timestamp(6), updated_at timestamp(6)
);
CREATE TABLE public.time_slots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id bigint NOT NULL REFERENCES public.doctors(user_id),
    slot_date date NOT NULL, start_time time(6) NOT NULL, end_time time(6) NOT NULL,
    status varchar(255) NOT NULL, created_at timestamp(6), updated_at timestamp(6),
    version bigint, CONSTRAINT legacy_slot_doctor_date_time UNIQUE (doctor_id, slot_date, start_time)
);
CREATE TABLE public.appointments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_date_time timestamp(6), status varchar(255), notes varchar(255),
    appointment_code varchar(255) NOT NULL UNIQUE,
    created_at timestamp(6), updated_at timestamp(6),
    doctor_id bigint NOT NULL REFERENCES public.doctors(user_id),
    patient_id bigint NOT NULL REFERENCES public.patients(user_id),
    time_slot_id bigint REFERENCES public.time_slots(id),
    CONSTRAINT "legacy Slot Uniqueness" UNIQUE (time_slot_id)
);
CREATE TABLE public.notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES public.users(id), message varchar(1000) NOT NULL,
    is_read boolean NOT NULL, timestamp timestamp(6)
);
CREATE TABLE public.otp_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(255) NOT NULL, otp_code varchar(6) NOT NULL,
    purpose varchar(50) NOT NULL, created_at timestamp(6) NOT NULL,
    expires_at timestamp(6) NOT NULL, is_used boolean NOT NULL, used_at timestamp(6)
);
CREATE INDEX idx_email_purpose ON public.otp_tokens (email, purpose);
CREATE INDEX idx_expires_at ON public.otp_tokens (expires_at);
CREATE TABLE public.audit_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint REFERENCES public.users(id), action varchar(500) NOT NULL,
    details varchar(2000), timestamp timestamp(6)
);
